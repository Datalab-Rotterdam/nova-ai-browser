// Copies the self-contained host (bundled dist, the nova-browser skill and a minimal
// package.json) into another project, e.g. Nova AI for VS Code or nova-ai-cli, which install it
// on startup with `cli.js install --auto`. Usage: npm run vendor:host -- <target folder>
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const target = process.argv[2];
if (!target) {
    console.error('Usage: npm run vendor:host -- <target folder>');
    process.exit(2);
}

const host = fileURLToPath(new URL('../packages/host/', import.meta.url));
const pkg = JSON.parse(readFileSync(join(host, 'package.json'), 'utf8'));
for (const file of ['dist/cli.js', 'dist/mcp.js', 'skill/nova-browser/SKILL.md']) {
    if (!existsSync(join(host, file))) {
        console.error(`Missing ${file}; run npm run build first.`);
        process.exit(1);
    }
}

const out = resolve(target);
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'dist'), { recursive: true });
for (const file of ['cli.js', 'mcp.js']) cpSync(join(host, 'dist', file), join(out, 'dist', file));
cpSync(join(host, 'skill'), join(out, 'skill'), { recursive: true });
writeFileSync(join(out, 'package.json'), `${JSON.stringify({
    name: pkg.name,
    version: pkg.version,
    private: true,
    type: 'module',
    description: 'Vendored copy of the Nova AI Browser host. Do not edit; update with `npm run vendor:host` in nova-ai-browser.'
}, null, 2)}\n`);
writeFileSync(join(out, 'README.md'), `# Nova AI Browser host ${pkg.version} (vendored)\n\nGenerated by \`npm run vendor:host\` in nova-ai-browser. Do not edit.\nRun \`node dist/cli.js install --auto\` to register it with the browsers and install the nova-browser skill.\n`);
console.log(`Vendored Nova AI Browser host ${pkg.version} into ${out}`);
