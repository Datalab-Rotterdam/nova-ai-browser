import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { compareVersions, install, installedVersion, launcherScript, runtimeDir, stableNodePath } from '../src/install';
import { HOST_NAME } from '../src/paths';
import { VERSION } from '../src/version';

const supported = process.platform === 'darwin' || process.platform === 'linux';

describe.skipIf(!supported)('install (startup auto mode)', () => {
    let home: string;
    const saved = { ...process.env };
    const edgeDir = () => process.platform === 'darwin'
        ? join(home, 'Library', 'Application Support', 'Microsoft Edge')
        : join(home, '.config', 'microsoft-edge');

    beforeEach(() => {
        home = mkdtempSync(join(tmpdir(), 'nova-install-'));
        process.env.HOME = home;
        delete process.env.XDG_CONFIG_HOME;
        process.env.NOVA_AI_BROWSER_HOME = join(home, '.nova-ai-browser');
        mkdirSync(edgeDir(), { recursive: true });
    });
    afterEach(() => {
        process.env = { ...saved };
        rmSync(home, { recursive: true, force: true });
    });

    it('copies the runtime, writes the wrapper and registers installed browsers only', () => {
        const result = install({ extensionIds: [], userDataDirs: [], auto: true });
        expect(result).toMatchObject({ version: VERSION, usedThisVersion: true, changed: true, browsers: ['Microsoft Edge'], newBrowsers: ['Microsoft Edge'] });
        expect(existsSync(join(runtimeDir(VERSION), 'dist', 'cli.js'))).toBe(true);
        expect(existsSync(join(runtimeDir(VERSION), 'skill', 'nova-browser', 'SKILL.md'))).toBe(true);

        const wrapper = readFileSync(join(home, '.nova-ai-browser', 'bin', 'nova-ai-browser-host'), 'utf8');
        expect(wrapper).toContain('Generated by Nova AI - do not edit');
        expect(wrapper).toContain(join(runtimeDir(VERSION), 'dist', 'cli.js'));

        const manifest = JSON.parse(readFileSync(join(edgeDir(), 'NativeMessagingHosts', `${HOST_NAME}.json`), 'utf8'));
        expect(manifest.path).toBe(join(home, '.nova-ai-browser', 'bin', 'nova-ai-browser-host'));
        expect(manifest.allowed_origins).toEqual(['chrome-extension://lnoimoijcjpcebjepmenoepmhbdgnipo/']);
        // Browsers that are not installed get nothing.
        expect(existsSync(join(home, 'Library', 'Application Support', 'Google'))).toBe(false);
    });

    it('changes nothing when everything is current', () => {
        install({ extensionIds: [], userDataDirs: [], auto: true });
        const again = install({ extensionIds: [], userDataDirs: [], auto: true });
        expect(again).toMatchObject({ changed: false, newBrowsers: [] });
    });

    it('never replaces a newer installed host in auto mode', () => {
        const newer = runtimeDir('99.0.0');
        mkdirSync(join(newer, 'dist'), { recursive: true });
        writeFileSync(join(newer, 'dist', 'cli.js'), '// newer host');
        expect(installedVersion()).toBe('99.0.0');

        const result = install({ extensionIds: [], userDataDirs: [], auto: true });
        expect(result).toMatchObject({ version: '99.0.0', usedThisVersion: false });
        expect(readFileSync(join(home, '.nova-ai-browser', 'bin', 'nova-ai-browser-host'), 'utf8')).toContain(join(newer, 'dist', 'cli.js'));

        // An explicit install (not auto) uses its own version.
        expect(install({ extensionIds: [], userDataDirs: [] }).version).toBe(VERSION);
    });
});

describe('launcherScript', () => {
    it('runs Electron as Node when needed', () => {
        const electron = launcherScript({ path: '/Apps/Code Helper', electron: true }, '/h/cli.js', 'call', 'x');
        expect(electron.unix).toContain('ELECTRON_RUN_AS_NODE=1 exec "/Apps/Code Helper" "/h/cli.js" call "$@"');
        expect(electron.cmd).toContain('set ELECTRON_RUN_AS_NODE=1');
        const node = launcherScript({ path: '/usr/bin/node', electron: false }, '/h/cli.js', '', 'x');
        expect(node.unix).toContain('exec "/usr/bin/node" "/h/cli.js" "$@"');
        expect(node.unix).not.toContain('ELECTRON');
    });
});

describe('compareVersions', () => {
    it('orders semantic versions numerically', () => {
        expect(compareVersions('0.10.0', '0.9.9')).toBeGreaterThan(0);
        expect(compareVersions('1.0.0', '1.0.0')).toBe(0);
        expect(compareVersions('1.2.3-beta.1', '1.2.4')).toBeLessThan(0);
    });
});

describe('stableNodePath', () => {
    it('keeps paths that are not in a Homebrew Cellar', () => {
        expect(stableNodePath('/usr/local/bin/node')).toBe('/usr/local/bin/node');
    });

    it('falls back to the Cellar path when the opt/ link does not exist', () => {
        expect(stableNodePath('/nonexistent/Cellar/node@24/24.21.0/bin/node')).toBe('/nonexistent/Cellar/node@24/24.21.0/bin/node');
    });
});
